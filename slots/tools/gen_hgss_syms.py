#!/usr/bin/env python3
"""
hack (slots/): writes slots/hgss_syms.s, HeartGold's address for every symbol the slot-machine objects need.

usage: python3 tools/gen_hgss_syms.py MAIN_NEF_READELF.txt OBJ_DIR > hgss_syms.s
  MAIN_NEF_READELF.txt = `arm-none-eabi-readelf -sW main.nef` of a pret/pokeheartgold build that matches the US ROM
  (its sha1 checked against heartgold.us/rom.sha1).  Thumb functions are found by the "$t" mapping symbols.
Only main-code (arm9 + ITCM) symbols are allowed: the slot game runs while the field overlays are unloaded.
"""
import bisect
import collections
import re
import subprocess
import sys

MAIN_SECTIONS = ('4', '6', '7', '9')  # main, main .bss, ITCM, ITCM .bss in main.nef


def main():
    nefsyms, objdir = sys.argv[1], sys.argv[2]
    syms, maps = {}, collections.defaultdict(list)
    for line in open(nefsyms):
        p = line.split()
        if len(p) < 8 or not re.fullmatch(r'\d+:', p[0]):
            continue
        val, typ, bind, ndx, name = int(p[1], 16), p[3], p[4], p[6], p[7]
        if name in ('$t', '$a', '$d'):
            maps[ndx].append(val if name != '$t' else val | 0x80000000_00000000)
            continue
        if ndx in MAIN_SECTIONS and typ in ('FUNC', 'OBJECT', 'NOTYPE') and (bind == 'GLOBAL' or name not in syms):
            syms[name] = (val, ndx, typ)
    for k in maps:
        maps[k].sort(key=lambda v: v & 0xFFFFFFFF)
    keys = {k: [v & 0xFFFFFFFF for v in maps[k]] for k in maps}

    def is_thumb(val, ndx):
        i = bisect.bisect_right(keys[ndx], val) - 1
        return i >= 0 and bool(maps[ndx][i] >> 63)

    objs = [o for o in subprocess.run(f'ls {objdir}/*.o', shell=True, capture_output=True, text=True).stdout.split() if not o.endswith('hgss_syms.o')]
    nm = lambda *a: subprocess.run(['arm-none-eabi-nm', *a, *objs], capture_output=True, text=True).stdout
    undef = {l.split()[-1] for l in nm('-u').split('\n') if l.strip() and not l.endswith(':')}
    defined = {l.split()[-1] for l in nm('--defined-only').split('\n') if len(l.split()) == 3}
    need = sorted(undef - defined)

    out = ['@ generated by slots/tools/gen_hgss_syms.py - HeartGold (US) addresses for the slot machine overlay',
           '.syntax unified', '.text']
    missing = []
    for n in need:
        if n not in syms:
            missing.append(n)
            continue
        v, ndx, typ = syms[n]
        out.append('.global %s' % n)
        if typ == 'OBJECT':
            out.append('.set %s, 0x%08X' % (n, v))
        elif is_thumb(v, ndx):
            out.append('.thumb_set %s, 0x%08X' % (n, v))
        else:
            out.append('.type %s, %%function\n.set %s, 0x%08X' % (n, n, v))
    if missing:
        sys.exit('not in HeartGold main code: ' + ' '.join(missing))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
