#!/usr/bin/env python3
"""
hack (Build 78): generate src/field/static_pool.c for the static encounter randomizer (src/field/static_randomizer.c).

with the randomizer on:
 - the Snorlax roadblocks, the Eevee gifts, Part 1's Magikarp salesman and the Fighting Dojo's Hitmonlee/Hitmonchan
   become a Pokemon with no evolution family at all (neither evolves nor evolves from anything; the Game Corner
   prizes' single-stage rule), legendaries, sub-legendaries, mythicals, Ultra Beasts and Paradox Pokemon left out.
 - every legendary, sub-legendary or mythical static encounter and the roaming Pokemon become one of the legendaries,
   sub-legendaries and mythicals.

run from the repo root:  python3 scripts/hack/gen_static_pool.py
"""
import re

SPECIES_H = "include/constants/species.h"
OUT = "src/field/static_pool.c"

defs = {}
for name, val in re.findall(r"#define (SPECIES_\w+)\s+(\d+)\b", open(SPECIES_H).read()):
    defs.setdefault(name, int(val))
canonical = {n: v for n, v in defs.items() if 1 <= v <= 1075 and not (494 <= v <= 543)}

evo = open("data/Evolutions.c").read()
evolves, targets = set(), set()
for name, body in re.findall(r"\[(SPECIES_\w+)\] = \{\s*\.entries = \{(.*?)\n        \},", evo, re.S):
    for method, target in re.findall(r"\{ (EVO_\w+), [^,]+, (SPECIES_\w+) \}", body):
        if method != "EVO_NONE" and target != "SPECIES_NONE":
            evolves.add(name)
            targets.add(target)
base_of = {n: max((b for b in canonical if n.startswith(b + "_")), key=len, default=None) for n in targets}
targets |= {b for b in base_of.values() if b}

pokemon_h = open("include/pokemon.h").read()
def macro(name):
    return set(re.findall(r"SPECIES_\w+", re.search(r"#define " + name + r"\(species\)(.*?)\n\n", pokemon_h, re.S).group(1)))
legend = (macro("IS_SPECIES_LEGENDARY") | macro("IS_SPECIES_SUBLEGEND") | macro("IS_SPECIES_MYTHICAL") | {"SPECIES_MARSHADOW"}) - {"SPECIES_SHIINOTIC"}
paradox = macro("IS_SPECIES_PARADOX_FORM") | {"SPECIES_GOUGING_FIRE", "SPECIES_RAGING_BOLT", "SPECIES_IRON_BOULDER", "SPECIES_IRON_CROWN"}
excluded = legend | macro("IS_SPECIES_ULTRA_BEAST") | paradox

single = sorted(canonical[n] for n in canonical if n not in evolves and n not in targets and n not in excluded)
legends = sorted(canonical[n] for n in legend if n in canonical)
names = {v: n for n, v in canonical.items()}

with open(OUT, "w") as f:
    f.write("// generated by scripts/hack/gen_static_pool.py - do not edit by hand\n\n")
    f.write('#include "types.h"\n#include "constants/species.h"\n\n')
    for label, lst in (("sStaticSinglePool", single), ("sStaticLegendPool", legends)):
        f.write(f"const u16 {label}[] = {{\n")
        for v in lst:
            f.write(f"    {names[v]},\n")
        f.write("};\n")
        f.write(f"const u16 {label}Count = {len(lst)};\n\n")
print("single-stage:", len(single), "legendary/mythical:", len(legends))
print(" ", ", ".join(names[v][8:].title() for v in single))
print(" ", ", ".join(names[v][8:].title() for v in legends))
