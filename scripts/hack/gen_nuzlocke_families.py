#!/usr/bin/env python3
"""
hack: generate src/battle/nuzlocke_families.c for the Nuzlocke dupes clause.

sNuzlockeFamilyRoot[species] = the first stage of that species' evolution family
(e.g. Pichu, Pikachu and Raichu all map to Pichu).  forms are folded into their base
species, so Alolan Rattata counts as a Rattata.

run from the repo root:  python3 scripts/hack/gen_nuzlocke_families.py
"""
import re

SPECIES_H = "include/constants/species.h"
EVOS_C = "data/Evolutions.c"
FORMS_C = "data/PokeFormDataTbl.c"
OUT = "src/battle/nuzlocke_families.c"
MAX = 1075

ids = {}
for name, val in re.findall(r"#define (SPECIES_\w+)\s+(\d+)\b", open(SPECIES_H).read()):
    ids.setdefault(name, int(val))
names = {}
for n, v in ids.items():
    names.setdefault(v, n)

# form species -> base species
form_base = {}
for base, body in re.findall(r"\[(SPECIES_\w+)\] = \{(.*?)\}", open(FORMS_C).read(), re.S):
    for f in re.findall(r"(?:NEEDS_REVERSION \| )?(SPECIES_\w+)", body):
        form_base.setdefault(f, base)


def canon(name):
    seen = set()
    while name in form_base and name not in seen:
        seen.add(name)
        name = form_base[name]
    v = ids.get(name, 0)
    return v if 1 <= v <= MAX else 0


parent = list(range(MAX + 1))


def find(x):
    while parent[x] != x:
        parent[x] = parent[parent[x]]
        x = parent[x]
    return x


prev = {}  # child -> parent stage (to find the first stage)
for src, body in re.findall(r"\n    \[(SPECIES_\w+)\] = \{(.*?)\n    \},", open(EVOS_C).read(), re.S):
    a = canon(src)
    if not a:
        continue
    for target in re.findall(r"\{ EVO_\w+, [^,]+, (SPECIES_\w+) \}", body):
        b = canon(target)
        if not b or b == a:
            continue
        parent[find(b)] = find(a)
        prev.setdefault(b, a)

# root = the member of the family with no pre-evolution (lowest id breaks ties)
members = {}
for s in range(1, MAX + 1):
    if s in names and not (494 <= s <= 543):
        members.setdefault(find(s), []).append(s)
root_of = {}
for group in members.values():
    firsts = [s for s in group if s not in prev] or group
    r = min(firsts)
    for s in group:
        root_of[s] = r

with open(OUT, "w") as f:
    f.write("// generated by scripts/hack/gen_nuzlocke_families.py - do not edit by hand\n\n")
    f.write('#include "types.h"\n#include "constants/species.h"\n\n')
    f.write("// first stage of each species' evolution family (dupes clause)\n")
    f.write(f"const u16 sNuzlockeFamilyRoot[{MAX + 1}] = {{\n")
    for s in sorted(root_of):
        f.write(f"    [{names[s]}] = {names[root_of[s]]},\n")
    f.write("};\n")

multi = sum(1 for g in members.values() if len(g) > 1)
print(f"species: {len(root_of)}, families: {len(members)}, multi-stage families: {multi}")
for test in ("SPECIES_RAICHU", "SPECIES_KINGDRA", "SPECIES_ANNIHILAPE", "SPECIES_HYDRAPPLE", "SPECIES_SYLVEON", "SPECIES_KINGAMBIT"):
    print(test[8:], "->", names[root_of[ids[test]]][8:])
