#!/usr/bin/env python3
"""hack: Part 2's (HeartGold's own) in-game trade scripts name their species in the text ("Do you have BELLSPROUT?"),
but the trade randomizer (src/field/trade_randomizer.c) changes the species, so the dialogue lied.

For each trade this writes
  data/scr_seq/scr_seq_00NNN_P2_TRADE_<map>.s  - HeartGold's script member as bytes, with the trade script's first
      play_se + lockall (6 bytes) replaced by a call to a subroutine appended at the end that plays them, loads the
      trade and buffers the asked species into STRVAR 0 and the offered one into STRVAR 1 (vars 0x8006/0x8007)
  data/text/NNN.txt - the map's text with the two species names replaced by {STRVAR_1 1, 0, 0} / {STRVAR_1 1, 1, 0}
run from the repo root with the venv (reads rom.nds; needs tools/msgenc)."""
import os, struct, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(__file__))

def read_narc(p):
    d = open(p, 'rb').read(); o = 16
    assert d[o:o+4] == b'BTAF'; n = struct.unpack_from('<I', d, o+8)[0]; fat = [struct.unpack_from('<II', d, o+12+8*i) for i in range(n)]
    o += struct.unpack_from('<I', d, o+4)[0]; o += struct.unpack_from('<I', d, o+4)[0]; img = o + 8
    return [d[img+a:img+b] for a, b in fat]

arm9 = open('base/arm9.bin', 'rb').read(); HDR = 0xf6be0
def hdr(m):
    h = struct.unpack_from('<BBHHHHHHHHH', arm9, HDR + 24*m)
    return dict(scripts=h[4], msg=h[6])

# map, script id, trade no, asked species name as in the text, offered species name
TRADES = [
    (162, 2, 0, 'BELLSPROUT', 'ONIX'),
    (195, 4, 1, 'DROWZEE', 'MACHOP'),
    (228, 1, 2, 'KRABBY', 'VOLTORB'),
    (290, 1, 3, 'DRAGONAIR', 'DODRIO'),
    (467, 7, 8, 'DUGTRIO', 'MAGNETON'),
    (489, 6, 8, 'DUGTRIO', 'MAGNETON'),
    (475, 2, 9, 'HAUNTER', 'XATU'),
]
import ndspy.rom, ndspy.narc
_rom = ndspy.rom.NintendoDSRom.fromFile('rom.nds')  # HeartGold's own files (base/ is the built, patched copy)
SCR = ndspy.narc.NARC(_rom.getFileByName('a/0/1/2')).files; MSG = ndspy.narc.NARC(_rom.getFileByName('a/0/2/7')).files
done_msg = set()
for m, sid, tno, ask, give in TRADES:
    h = hdr(m); mem = h['scripts']; d = SCR[mem]
    offs = []; j = 0
    while struct.unpack_from('<H', d, j)[0] != 0xFD13:
        offs.append(j + 4 + struct.unpack_from('<i', d, j)[0]); j += 4
    st = offs[sid - 1]
    assert struct.unpack_from('<HHH', d, st) == (73, 1500, 96), (m, sid, d[st:st+6].hex())
    b = lambda bs: '\t.byte ' + ', '.join('0x%02x' % x for x in bs) + '\n' if bs else ''
    out = ['// hack: HeartGold\'s script member %d (map %d) as bytes; script %d (trade %d) starts with a call to _p2Trade,\n' % (mem, m, sid, tno),
           '// which buffers the randomized species for the text.  generated by scripts/hack/fix_p2_trades.py\n\n',
           '.include "asm/include/scriptmacros.inc"\n\n.data\n\n']
    for k in range(0, st, 16): out.append(b(d[k:min(k+16, st)]))
    out.append('\tcall _p2Trade\n')
    rest = d[st+6:]
    for k in range(0, len(rest), 16): out.append(b(rest[k:k+16]))
    out.append('\n_p2Trade:\n\tplay_se 1500\n\tlockall\n\tload_npc_trade %d\n\tget_offered_species 0x8006\n\tnpc_trade_get_req_species 0x8007\n\tnpc_trade_end\n' % tno)
    out.append('\tbuffer_species_name 0, 0x8007, 0, 0\n\tbuffer_species_name 1, 0x8006, 0, 0\n\treturn\n\t.balign 4, 0\n')
    name = 'data/scr_seq/scr_seq_%05d_P2_TRADE_%d.s' % (mem, m)
    open(name, 'w').write(''.join(out)); print('wrote', name)
    msg = h['msg']
    if msg in done_msg: continue
    done_msg.add(msg)
    with tempfile.TemporaryDirectory() as td:
        open(td + '/m.bin', 'wb').write(MSG[msg])
        subprocess.run(['tools/msgenc', '-d', '-c', 'charmap.txt', td + '/m.bin', td + '/m.txt'], check=True, capture_output=True)
        t = open(td + '/m.txt', 'rb').read().decode('utf-8')
    lines = t.split('\r\n'); n = 0
    for i, l in enumerate(lines):
        if ask in l or give in l:
            if 'Lt. Surge' in l: continue
            l2 = l.replace(ask, '{STRVAR_1 1, 0, 0}').replace(give, '{STRVAR_1 1, 1, 0}')
            l2 = l2.replace(' a {STRVAR_1 1, 0, 0}', ' {STRVAR_1 1, 0, 0}')
            lines[i] = l2; n += 1
    open('data/text/%03d.txt' % msg, 'wb').write('\r\n'.join(lines).encode('utf-8'))
    print('wrote data/text/%03d.txt' % msg, n, 'lines')
