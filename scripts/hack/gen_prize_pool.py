#!/usr/bin/env python3
"""
hack: generate src/prize_pool.c for Part 1's Rocket Game Corner prize Pokemon.

the five FireRed prize Pokemon (Abra, Clefairy, Dratini, Scyther, Porygon) are randomized per save: each slot picks a
Pokemon that neither evolves nor evolves from anything (a single-stage Pokemon, like RadiantRed's coin prizes), from a
base stat total band that rises with the price.  legendaries, mythicals, sub-legendaries and Ultra Beasts are left out
(the same exclusions as the wild pool).

run from the repo root:  python3 scripts/hack/gen_prize_pool.py
"""
import re

SPECIES_H = "include/constants/species.h"
OUT = "src/prize_pool.c"
# (min BST, max BST) per prize slot, cheapest first
BANDS = [(0, 399), (400, 449), (450, 489), (490, 519), (520, 999)]

defs = {}
for name, val in re.findall(r"#define (SPECIES_\w+)\s+(\d+)\b", open(SPECIES_H).read()):
    defs.setdefault(name, int(val))
canonical = {n: v for n, v in defs.items() if 1 <= v <= 1075 and not (494 <= v <= 543)}

species_c = open("data/Species.c").read()
bst = {}
for name, body in re.findall(r"\n    \[(SPECIES_\w+)\] = \{(.*?)\n    \},", species_c, re.S):
    stats = re.search(r"\.baseStats = \{(.*?)\}", body, re.S)
    if name in canonical and stats:
        bst[name] = sum(int(x) for x in re.findall(r"= (\d+)", stats.group(1)))

evo = open("data/Evolutions.c").read()
evolves, targets = set(), set()
for name, body in re.findall(r"\[(SPECIES_\w+)\] = \{\s*\.entries = \{(.*?)\n        \},", evo, re.S):
    for method, target in re.findall(r"\{ (EVO_\w+), [^,]+, (SPECIES_\w+) \}", body):
        if method != "EVO_NONE" and target != "SPECIES_NONE":
            evolves.add(name)
            targets.add(target)
# a form target (e.g. SPECIES_EXEGGUTOR_ALOLAN) also marks its base species as an evolution
base_of = {n: max((b for b in canonical if n.startswith(b + "_")), key=len, default=None) for n in targets}
targets |= {b for b in base_of.values() if b}

pokemon_h = open("include/pokemon.h").read()
excluded = set()
for macro in ("IS_SPECIES_LEGENDARY", "IS_SPECIES_MYTHICAL", "IS_SPECIES_SUBLEGEND", "IS_SPECIES_ULTRA_BEAST"):
    body = re.search(r"#define " + macro + r"\(species\)(.*?)\n\n", pokemon_h, re.S).group(1)
    excluded |= set(re.findall(r"SPECIES_\w+", body))
excluded.discard("SPECIES_SHIINOTIC")
# as in the wild pool: Marshadow (a mythical under every config) and the legendary-counterpart Paradox Pokemon
excluded |= {"SPECIES_MARSHADOW", "SPECIES_WALKING_WAKE", "SPECIES_IRON_LEAVES", "SPECIES_GOUGING_FIRE",
             "SPECIES_RAGING_BOLT", "SPECIES_IRON_BOULDER", "SPECIES_IRON_CROWN"}

single = sorted((bst[n], canonical[n], n) for n in canonical
                if n in bst and n not in evolves and n not in targets and n not in excluded)
tiers = [[(b, n) for b, _, n in single if lo <= b <= hi] for lo, hi in BANDS]

with open(OUT, "w") as f:
    f.write("// generated by scripts/hack/gen_prize_pool.py - do not edit by hand\n\n")
    f.write('#include "types.h"\n#include "constants/species.h"\n\n')
    for i, t in enumerate(tiers):
        f.write(f"static const u16 sPrizeTier{i}[] = {{\n")
        for b, n in t:
            f.write(f"    {n}, // {b}\n")
        f.write("};\n\n")
    f.write("const u16 *const sPrizeTiers[5] = { " + ", ".join(f"sPrizeTier{i}" for i in range(5)) + " };\n")
    f.write("const u16 sPrizeTierCounts[5] = { " + ", ".join(str(len(t)) for t in tiers) + " };\n")
print("single-stage:", len(single), "tiers:", [len(t) for t in tiers])
for t in tiers:
    print(" ", ", ".join(n[8:].title() for _, n in t))
