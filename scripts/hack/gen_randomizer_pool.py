#!/usr/bin/env python3
"""
hack: generate src/randomizer_pool.c for the area randomizer.

- sBaseStatTotals[species]: BST of every canonical species (index = species id, 0 for none/placeholders)
- sWildPool[]: species allowed to appear as randomized wild Pokemon, sorted by BST (ascending)
- src/field/regional_pool.c: the regional forms, which only the Safari Zone hands out

excluded from the pool: every starter line (Gens 1-9), legendaries, mythicals, sub-legendaries,
Ultra Beasts, and the legendary-counterpart Paradox Pokemon.  battle-only forms (Mega, Gigantamax,
Terastal, etc.) never appear because only base species ids are used.

run from the repo root:  python3 scripts/hack/gen_randomizer_pool.py
"""
import re

SPECIES_C = "data/Species.c"
SPECIES_H = "include/constants/species.h"
POKEMON_H = "include/pokemon.h"
RANDOMIZER_C = "src/randomizer.c"
OUT = "src/randomizer_pool.c"

defs = {}
for name, val in re.findall(r"#define (SPECIES_\w+)\s+(\d+)\b", open(SPECIES_H).read()):
    defs.setdefault(name, int(val))

canonical = {n: v for n, v in defs.items() if 1 <= v <= 1075 and not (494 <= v <= 543)}

# base stats
species_c = open(SPECIES_C).read()
bst = {}
for name, body in re.findall(r"\n    \[(SPECIES_\w+)\] = \{(.*?)\n    \},", species_c, re.S):
    if name not in canonical:
        continue
    stats = re.search(r"\.baseStats = \{(.*?)\}", body, re.S)
    if not stats:
        continue
    total = sum(int(x) for x in re.findall(r"= (\d+)", stats.group(1)))
    bst[name] = total

# exclusions
pokemon_h = open(POKEMON_H).read()
excluded = set()
for macro in ("IS_SPECIES_LEGENDARY", "IS_SPECIES_MYTHICAL", "IS_SPECIES_SUBLEGEND", "IS_SPECIES_ULTRA_BEAST"):
    body = re.search(r"#define " + macro + r"\(species\)(.*?)\n\n", pokemon_h, re.S).group(1)
    excluded |= set(re.findall(r"SPECIES_\w+", body))
excluded |= {"SPECIES_MARSHADOW", "SPECIES_SHIINOTIC"} & set(canonical)  # EXTRA_MYTHICALS variants
excluded.discard("SPECIES_SHIINOTIC")  # only a "mythical" under VANILLA_MYTHICALS; it's a normal Pokemon
excluded |= {"SPECIES_WALKING_WAKE", "SPECIES_IRON_LEAVES", "SPECIES_GOUGING_FIRE",
             "SPECIES_RAGING_BOLT", "SPECIES_IRON_BOULDER", "SPECIES_IRON_CROWN"}
starter_block = re.search(r"sStarterLines\[3\]\[STARTER_LINES_PER_TYPE\]\[3\] = \{(.*?)\n\};", open(RANDOMIZER_C).read(), re.S).group(1)
starters = set(re.findall(r"SPECIES_\w+", starter_block))
assert len(starters) == 81, len(starters)
excluded |= starters

pool = sorted((bst[n], canonical[n], n) for n in canonical if n in bst and n not in excluded)
pool = [(total, n, n) for total, _, n in pool]  # (bst, encoded expression, label)

# regional forms (Alolan / Galarian / Hisuian / Paldean), stored as species | (form << 11)
# the form number is the 1-based position of the form under its base species in data/PokeFormDataTbl.c
form_tbl = open("data/PokeFormDataTbl.c").read()
form_of = {}
for base, body in re.findall(r"\[(SPECIES_\w+)\] = \{(.*?)\}", form_tbl, re.S):
    for i, f in enumerate(re.findall(r"(?:NEEDS_REVERSION \| )?(SPECIES_\w+)", body)):
        form_of.setdefault(f, (base, i + 1))
form_bst = {}
for name, body in re.findall(r"\n    \[(SPECIES_\w+)\] = \{(.*?)\n    \},", species_c, re.S):
    stats = re.search(r"\.baseStats = \{(.*?)\}", body, re.S)
    if stats:
        form_bst[name] = sum(int(x) for x in re.findall(r"= (\d+)", stats.group(1)))
all_names = re.findall(r"#define (SPECIES_\w+)\b", open(SPECIES_H).read())
regional = [n for n in all_names if re.search(r"_(ALOLAN|GALARIAN|HISUIAN)$", n)] + \
           ["SPECIES_WOOPER_PALDEAN", "SPECIES_TAUROS_COMBAT", "SPECIES_TAUROS_BLAZE", "SPECIES_TAUROS_AQUA"]
regional_excluded = {
    "SPECIES_ARTICUNO_GALARIAN", "SPECIES_ZAPDOS_GALARIAN", "SPECIES_MOLTRES_GALARIAN",          # legendary
    "SPECIES_TYPHLOSION_HISUIAN", "SPECIES_SAMUROTT_HISUIAN", "SPECIES_DECIDUEYE_HISUIAN",      # starters
    "SPECIES_DARMANITAN_ZEN_MODE_GALARIAN",                                                     # battle form
}
added = []
regional_pool = []
for n in regional:
    if n in regional_excluded or n not in form_of or n not in form_bst:
        continue
    base, form = form_of[n]
    if base in excluded:
        continue
    regional_pool.append((form_bst[n], f"{base} | ({form} << 11)", n))
    added.append(n)
regional_pool.sort(key=lambda x: x[0])
pool.sort(key=lambda x: x[0])

with open(OUT, "w") as f:
    f.write("// generated by scripts/hack/gen_randomizer_pool.py - do not edit by hand\n\n")
    f.write('#include "types.h"\n#include "constants/species.h"\n\n')
    f.write("const u16 sBaseStatTotals[1076] = {\n")
    for n, v in sorted(canonical.items(), key=lambda x: x[1]):
        if n in bst:
            f.write(f"    [{n}] = {bst[n]},\n")
    f.write("};\n\n")
    f.write(f"const u16 sWildPoolCount = {len(pool)};\n\n")
    f.write("// species | (form << 11), sorted by base stat total, ascending\n")
    f.write(f"const u16 sWildPool[{len(pool)}] = {{\n")
    for total, expr, label in pool:
        f.write(f"    {expr}, // {label[8:]} {total}\n")
    f.write("};\n\n")

# regional forms only appear in the Safari Zone (src/field/safari_randomizer.c)
with open("src/field/regional_pool.c", "w") as f:
    f.write("// generated by scripts/hack/gen_randomizer_pool.py - do not edit by hand\n\n")
    f.write('#include "types.h"\n#include "constants/species.h"\n\n')
    f.write(f"const u16 sRegionalPoolCount = {len(regional_pool)};\n\n")
    f.write("// regional forms (species | (form << 11)) and their base stat totals, sorted by base stat total\n")
    f.write(f"const u16 sRegionalPool[{len(regional_pool)}][2] = {{\n")
    for total, expr, label in regional_pool:
        f.write(f"    {{ {expr}, {total} }}, // {label[8:]}\n")
    f.write("};\n")

print(f"canonical species: {len(canonical)}, with stats: {len(bst)}, excluded: {len(excluded & set(canonical))}, regional forms (Safari only): {len(added)}, pool: {len(pool)}")
print("regional:", ", ".join(a[8:] for a in added))
