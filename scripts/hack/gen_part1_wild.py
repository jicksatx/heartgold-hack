#!/usr/bin/env python3
"""
hack: Part 1 (FireRed Kanto) wild encounters, taken from FireRed (pret/pokefirered src/data/wild_encounters.json).

writes data/EncountersPart1.inc, included at the end of data/Encounters.c: member 143 + <HeartGold bank> holds the
FireRed table for that bank (marked with dummy[0] = 1).  in Part 1 the encounter loader (src/randomizer.c) reads
that member instead of the HeartGold one when it's marked; the area randomizer then runs on it as usual.

usage: python3 scripts/hack/gen_part1_wild.py <path to pokefirered checkout>
"""
import json
import sys

PFR = sys.argv[1] if len(sys.argv) > 1 else "../pfr"
OUT = "data/EncountersPart1.inc"
PART1_OFFSET = 143

# FireRed map -> HeartGold encounter bank(s)
MAPPING = {
    "MAP_PALLET_TOWN": ["ENCDATA_T01_PALLET_TOWN"],
    "MAP_VIRIDIAN_CITY": ["ENCDATA_T02_VIRIDIAN_CITY"],
    "MAP_CERULEAN_CITY": ["ENCDATA_T04_CERULEAN_CITY"],
    "MAP_VERMILION_CITY": ["ENCDATA_T06_VERMILION_CITY"],
    "MAP_CELADON_CITY": ["ENCDATA_T07_CELADON_CITY"],
    "MAP_FUCHSIA_CITY": ["ENCDATA_T08_FUCHSIA_CITY"],
    "MAP_CINNABAR_ISLAND": ["ENCDATA_T09_CINNABAR_ISLAND"],
    "MAP_ROUTE1": ["ENCDATA_R01_ROUTE_1"],
    "MAP_ROUTE2": ["ENCDATA_R02_ROUTE_2_SOUTH_BELOW_VIRIDIAN_FOREST", "ENCDATA_R02R0101_ROUTE_2_NORTH_ABOVE_VIRIDIAN_FOREST"],
    "MAP_ROUTE3": ["ENCDATA_R03_ROUTE_3"],
    "MAP_ROUTE4": ["ENCDATA_R04_ROUTE_4"],
    "MAP_ROUTE5": ["ENCDATA_R05_ROUTE_5"],
    "MAP_ROUTE6": ["ENCDATA_R06_ROUTE_6"],
    "MAP_ROUTE7": ["ENCDATA_R07_ROUTE_7"],
    "MAP_ROUTE8": ["ENCDATA_R08_ROUTE_8"],
    "MAP_ROUTE9": ["ENCDATA_R09_ROUTE_9"],
    "MAP_ROUTE10": ["ENCDATA_R10_ROUTE_10"],
    "MAP_ROUTE11": ["ENCDATA_R11_ROUTE_11"],
    "MAP_ROUTE12": ["ENCDATA_R12_ROUTE_12"],
    "MAP_ROUTE13": ["ENCDATA_R13_ROUTE_13"],
    "MAP_ROUTE14": ["ENCDATA_R14_ROUTE_14"],
    "MAP_ROUTE15": ["ENCDATA_R15_ROUTE_15"],
    "MAP_ROUTE16": ["ENCDATA_R16R0301_ROUTE_16"],
    "MAP_ROUTE17": ["ENCDATA_R17_ROUTE_17"],
    "MAP_ROUTE18": ["ENCDATA_R18_ROUTE_18"],
    "MAP_ROUTE19": ["ENCDATA_W19_ROUTE_19"],
    "MAP_ROUTE20": ["ENCDATA_W20_ROUTE_20"],
    "MAP_ROUTE21_NORTH": ["ENCDATA_W21_ROUTE_21"],
    "MAP_ROUTE22": ["ENCDATA_R22_ROUTE_22"],
    "MAP_ROUTE24": ["ENCDATA_R24_ROUTE_24"],
    "MAP_ROUTE25": ["ENCDATA_R25_ROUTE_25"],
    "MAP_VIRIDIAN_FOREST": ["ENCDATA_D46R0101_VIRIDIAN_FOREST"],
    "MAP_MT_MOON_1F": ["ENCDATA_D02R0101_MT_MOON_1F"],
    "MAP_MT_MOON_B2F": ["ENCDATA_D02R0102_MT_MOON_2F"],
    "MAP_DIGLETTS_CAVE_B1F": ["ENCDATA_D01R0101_DIGLETTS_CAVE"],
    "MAP_ROCK_TUNNEL_1F": ["ENCDATA_D05R0101_ROCK_TUNNEL_1F"],
    "MAP_ROCK_TUNNEL_B1F": ["ENCDATA_D05R0102_ROCK_TUNNEL_B1F"],
    "MAP_VICTORY_ROAD_1F": ["ENCDATA_D43R0101_VICTORY_ROAD_1F"],
    "MAP_VICTORY_ROAD_2F": ["ENCDATA_D43R0102_VICTORY_ROAD_2F"],
    "MAP_VICTORY_ROAD_3F": ["ENCDATA_D43R0103_VICTORY_ROAD_3F"],
    "MAP_SEAFOAM_ISLANDS_1F": ["ENCDATA_D11R0101_SEAFOAM_ISLANDS_1F"],
    "MAP_SEAFOAM_ISLANDS_B1F": ["ENCDATA_D11R0102_SEAFOAM_ISLANDS_B1F"],
    "MAP_SEAFOAM_ISLANDS_B2F": ["ENCDATA_D11R0103_SEAFOAM_ISLANDS_B2F"],
    "MAP_SEAFOAM_ISLANDS_B3F": ["ENCDATA_D11R0104_SEAFOAM_ISLANDS_B3F"],
    "MAP_SEAFOAM_ISLANDS_B4F": ["ENCDATA_D11R0105_SEAFOAM_ISLANDS_B4F"],
    "MAP_POKEMON_MANSION_1F": ["ENCDATA_D18R0101_BURNED_TOWER_1F"],
    "MAP_POKEMON_MANSION_B1F": ["ENCDATA_D18R0102_BURNED_TOWER_B1F"],
    "MAP_CERULEAN_CAVE_1F": ["ENCDATA_D03R0101_CERULEAN_CAVE_1F"],
    "MAP_CERULEAN_CAVE_2F": ["ENCDATA_D03R0102_CERULEAN_CAVE_B1F"],
    "MAP_CERULEAN_CAVE_B1F": ["ENCDATA_D03R0103_CERULEAN_CAVE_B2F"],
}

enc = json.load(open(f"{PFR}/src/data/wild_encounters.json"))["wild_encounter_groups"][0]["encounters"]
fr = {e["map"]: e for e in enc if e["base_label"].endswith("_FireRed")}


def slot(m):
    return "{ %d, %d, %s }" % (m["min_level"], m["max_level"], m["species"])


def none_slot():
    return "{ 0, 0, SPECIES_NONE }"


out = ["// generated by scripts/hack/gen_part1_wild.py from FireRed's wild encounters - do not edit by hand", ""]
for frmap, banks in MAPPING.items():
    e = fr[frmap]
    land = e.get("land_mons", {}).get("mons", [])
    water = e.get("water_mons", {}).get("mons", [])
    smash = e.get("rock_smash_mons", {}).get("mons", [])
    fish = e.get("fishing_mons", {}).get("mons", [])
    old, good, sup = fish[0:2], fish[2:5], fish[5:10]
    # FireRed rods have 2/3/5 slots, HeartGold has 5 each (40/40/15/4/1)
    old5 = [old[0], old[0], old[1], old[1], old[1]] if old else []
    good5 = [good[0], good[1], good[0], good[2], good[1]] if good else []
    for bank in banks:
        o = [f"    // {frmap}", f"    [{PART1_OFFSET} + {bank}] = {{"]
        o.append(f"        .rateWalk = {e.get('land_mons', {}).get('encounter_rate', 0)},")
        o.append(f"        .rateSurf = {e.get('water_mons', {}).get('encounter_rate', 0)},")
        o.append(f"        .rateRockSmash = {e.get('rock_smash_mons', {}).get('encounter_rate', 0)},")
        rate = e.get("fishing_mons", {}).get("encounter_rate", 0)
        o.append(f"        .rateOldRod = {rate}, .rateGoodRod = {rate}, .rateSuperRod = {rate},")
        o.append("        .dummy = { 1, 0 }, // marks a Part 1 table")
        if land:
            lv = ", ".join(str((m["min_level"] + m["max_level"] + 1) // 2) for m in land)
            sp = ", ".join(m["species"] for m in land)
            o.append("        .landSlots = {")
            o.append(f"            .levels = {{ {lv} }},")
            o.append(f"            .speciesMorning = {{ {sp} }},")
            o.append(f"            .speciesDay = {{ {sp} }},")
            o.append(f"            .speciesNight = {{ {sp} }},")
            o.append("        },")
        o.append("        .surfSlots = { " + ", ".join(slot(m) for m in water) + " }," if water else "        .surfSlots = { " + ", ".join([none_slot()] * 5) + " },")
        o.append("        .rockSmashSlots = { " + ", ".join(slot(m) for m in smash[:2]) + " }," if smash else "        .rockSmashSlots = { " + ", ".join([none_slot()] * 2) + " },")
        for name, slots in (("oldRodSlots", old5), ("goodRodSlots", good5), ("superRodSlots", sup)):
            o.append(f"        .{name} = {{ " + (", ".join(slot(m) for m in slots) if slots else ", ".join([none_slot()] * 5)) + " },")
        o.append("    },")
        out += o
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT, sum(len(b) for b in MAPPING.values()), "tables")
