#!/usr/bin/env python3
"""
hack: in-game trade randomization data (src/trade_randomizer.c).

the trader's requested species is turned into what the area randomizer turns it into in one wild area where it lives,
so the Pokemon asked for can always be caught in that save.  for each trade this finds that area (encounter bank):
Part 1's trades (26+) look in Part 1's FireRed tables (data/EncountersPart1.inc), HeartGold's in data/Encounters.c.
a requested species that isn't wild anywhere is replaced by its wild pre-evolution (PRE_EVO).  writes
data/NpcTradeAskBanks.h.

usage: python3 scripts/hack/gen_trade_banks.py   (after gen_npc_trades.py / gen_part1_wild.py)
"""
import re

PRE_EVO = {"RAICHU": "PIKACHU", "GOLDUCK": "PSYDUCK", "NIDORINO": "NIDORAN_M", "POLIWHIRL": "POLIWAG"}
FIRST_PART1 = 26


def species_numbers():
    return {k: int(v) for k, v in re.findall(r"#define SPECIES_(\w+)\s+(\d+)\b", open("include/constants/species.h").read())}


def tables(path, part1):
    banks = {k: int(v) for k, v in re.findall(r"(ENCDATA_\w+) = (\d+)", open("include/constants/encounter_tables.h").read())}
    src = open(path).read()
    pat = r"\[143 \+ (ENCDATA_\w+)\] = \{(.*?)\n    \}," if part1 else r"\n    \[(ENCDATA_\w+)\] = \{(.*?)\n    \},"
    out = []
    for name, body in re.findall(pat, src, re.S):
        land = body.split(".surfSlots")[0] if ".surfSlots" in body else body
        out.append((banks[name], name, set(re.findall(r"SPECIES_(\w+)", land)), set(re.findall(r"SPECIES_(\w+)", body))))
    return out


def main():
    num = species_numbers()
    rev = {v: k for k, v in num.items()}
    rows = re.findall(r"^    \{ (.*?) \}, // (\d+)", open("data/NpcTrades.c").read(), re.M)
    hg, p1 = tables("data/Encounters.c", False), tables("data/EncountersPart1.inc", True)
    lines = []
    for fields, no in rows:
        no = int(no)
        ask = fields.split(", ")[19]
        ask = ask.replace("SPECIES_", "") if ask.startswith("SPECIES_") else rev[int(ask)]
        tbls = p1 if no >= FIRST_PART1 else hg
        bank, used = 0xFFFF, ask
        for cand in (ask, PRE_EVO.get(ask)):
            if cand is None:
                continue
            hit = [t for t in tbls if cand in t[2]] or [t for t in tbls if cand in t[3]]
            if hit:
                bank, used = hit[0][0], cand
                break
        if bank == 0xFFFF:
            print(f"trade {no}: {ask} is not wild anywhere - random similar species")
        lines.append(f"    {{ {bank:#06x}, SPECIES_{used} }}, // {no}: {ask}" + (f" -> {hit[0][1]}" if bank != 0xFFFF else ""))
    out = ["// generated by scripts/hack/gen_trade_banks.py - do not edit by hand",
           "// per trade: encounter bank where the requested species (or its pre-evolution) is wild, that species",
           f"static const u16 sTradeAskBank[{len(rows)}][2] = {{"] + lines + ["};", ""]
    open("data/NpcTradeAskBanks.h", "w", newline="\n").write("\n".join(out))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
