# Part 1 order (trade numbers 26..): the INGAME_TRADE_* entries, FireRed's version
PART1 = ["MR_MIME", "JYNX", "NIDORAN", "FARFETCHD", "NIDORINOA", "LICKITUNG", "ELECTRODE", "TANGELA", "SEEL"]
ITEMS = {"ITEM_NONE": "0", "ITEM_FAB_MAIL": "0", "ITEM_STICK": "ITEM_LEEK"}


def title(name):
    return " ".join(w.capitalize() for w in name.split(" ")).replace("'", "’").replace("’d", "’D")


def parse():
    src = open(f"{PFR}/src/data/ingame_trades.h").read()
    src = re.sub(r"#if defined\(FIRERED\)(.*?)#else.*?#endif", r"\1", src, flags=re.S)  # FireRed's side
    out = {}
    for m in re.finditer(r"\[INGAME_TRADE_(\w+)\] =\s*\{(.*?)\n    \}", src, re.S):
        b = m.group(2) + "\n"
        g = lambda k: re.search(r"\." + k + r" = (.*?),?\n", b).group(1).strip().rstrip(",")
        ivs = [int(x) for x in re.search(r"\.ivs = \{(.*?)\}", b).group(1).split(",")]
        cond = [int(x) for x in re.search(r"\.conditions = \{(.*?)\}", b).group(1).split(",")]
        out[m.group(1)] = dict(nick=re.search(r'\.nickname = _\("(.*?)"\)', b).group(1), species=g("species"),
                               ivs=ivs, otId=g("otId"), cond=cond, pid=g("personality"), item=g("heldItem"),
                               ot=re.search(r'\.otName = _\("(.*?)"\)', b).group(1), otGender=g("otGender"),
                               sheen=g("sheen"), req=g("requestedSpecies"))
    return out


def main():
    trades = parse()
    rows = [", ".join(str(v) for v in t) for t in VANILLA]
    rows += [rows[0]] * (FIRST_P1 - len(VANILLA))  # fillers 13..25 (never used)
    nicks, ots = [], []
    for name in PART1:
        t = trades[name]
        hp, atk, df, spe, spa, spd = t["ivs"]
        item = ITEMS.get(t["item"], t["item"])
        rows.append(", ".join(str(v) for v in (t["species"], hp, atk, df, spe, spa, spd, 0, t["otId"], *t["cond"],
                                                t["pid"], item, 1 if t["otGender"] == "FEMALE" else 0, t["sheen"], 2,
                                                t["req"], 0)))
        nicks.append(title(t["nick"]))
        ots.append(title(t["ot"]))
    c = ['#include "../include/types.h"', '#include "../include/constants/species.h"', '#include "../include/constants/item.h"', "",
         "// generated by scripts/hack/gen_npc_trades.py - do not edit by hand", "// species, IVs (HP Atk Def Spe SpA SpD), ability (unused), OT id, contest x5, PID, held item, OT gender,",
         "// sheen, language, requested species, unused", "",
         f"const u32 __size[] = {{ {', '.join(['84'] * len(rows))} }};", "",
         f"const s32 __data[{len(rows)}][21] = {{"]
    for i, r in enumerate(rows):
        c.append(f"    {{ {r} }}, // {i}" + (f" {PART1[i - FIRST_P1]}" if i >= FIRST_P1 else ""))
    c.append("};")
    open("data/NpcTrades.c", "w").write("\n".join(c) + "\n")
    # msg 200: nickname N, OT name N + 13
    lines = VANILLA_NAMES + nicks + ["-"] * 4 + ots
    assert lines.index(ots[0]) == FIRST_P1 + 13
    open("data/text/200.txt", "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(rows)} trades; Part 1: " + ", ".join(f"{FIRST_P1 + i} {n}" for i, n in enumerate(PART1)))


if __name__ == "__main__":
    main()
